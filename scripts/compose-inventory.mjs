#!/usr/bin/env node
// Regenerates the Jetpack Compose area files in docs/compatibility/compose/ from AndroidX's published API
// signature files (compose/<lib>/api/<version>.txt on github.com/androidx/androidx, newest release per library).
// Needs network access; not run in CI.
//   node scripts/compose-inventory.mjs
// One row per public composable, Modifier extension, other top-level function and top-level type
// (overloads share a row). Status, Issue and Notes of rows already in the folder are kept; new rows are ⬜.
// The library versions used are written to docs/compatibility/versions.json (`compose`).
// Afterwards run `node scripts/api-coverage.mjs` to refresh the summary.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const dir = root + 'docs/compatibility/compose/';
const REPO = 'androidx/androidx', REF = 'androidx-main';
// AndroidX project path -> label shown in the Library column.
const LIBS = {
  'compose/runtime/runtime': 'runtime',
  'compose/ui/ui': 'ui',
  'compose/ui/ui-graphics': 'ui-graphics',
  'compose/ui/ui-text': 'ui-text',
  'compose/ui/ui-unit': 'ui-unit',
  'compose/ui/ui-geometry': 'ui-geometry',
  'compose/ui/ui-tooling-preview': 'ui-tooling-preview',
  'compose/foundation/foundation-layout': 'foundation-layout',
  'compose/foundation/foundation': 'foundation',
  'compose/animation/animation-core': 'animation-core',
  'compose/animation/animation': 'animation',
  'compose/material3/material3': 'material3',
  'navigation/navigation-compose': 'navigation-compose',
  'activity/activity-compose': 'activity-compose',
};
// Section -> area file (also listed in FRAMEWORKS in scripts/api-coverage.mjs).
const FILES = { Composables: 'composables', Modifiers: 'modifiers', 'Runtime (state, effects, composition)': 'runtime', 'Other functions and properties': 'functions', Types: 'types' };
const INTRO = 'Part of [Jetpack Compose API coverage](README.md): status legend, summary and how to add a row. Generated by `scripts/compose-inventory.mjs`; edit Status, Issue and Notes in place (they survive regeneration).';

// Newest release signature file: highest x.y.z, a final release beating its pre-releases.
const rank = (f) => {
  const m = f.match(/^(\d+)\.(\d+)\.(\d+)(?:-(alpha|beta|rc)(\d+))?\.txt$/);
  return m && [+m[1], +m[2], +m[3], { alpha: 0, beta: 1, rc: 2 }[m[4]] ?? 3, +(m[5] || 0)];
};
const cmp = (a, b) => {
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return a[i] - b[i];
  return 0;
};
async function get(url, json) {
  const r = await fetch(url, { headers: json ? { Accept: 'application/vnd.github+json' } : {} });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return json ? r.json() : r.text();
}

const api = new Map(); // key -> { section, libs: Set, deprecated, experimental }
const versions = [];
for (const [path, lib] of Object.entries(LIBS)) {
  const files = (await get(`https://api.github.com/repos/${REPO}/contents/${path}/api?ref=${REF}`, true)).map((f) => f.name).filter(rank);
  const file = files.sort((a, b) => cmp(rank(a), rank(b))).pop();
  versions.push(`${lib} ${file.slice(0, -4)}`);
  let pkg = '', skipPkg = false, cls = null;
  // Not app-facing: compiler hooks, internal APIs, and internal/tooling packages (ui-tooling-preview's
  // androidx.compose.ui.tooling.preview is kept).
  const INTERNAL = /@[\w.]*(ComposeCompilerApi|Internal\w*Api|PublishedApi|InaccessibleFromKotlin)\b/;
  for (const line of (await get(`https://raw.githubusercontent.com/${REPO}/${REF}/${path}/api/${file}`)).split('\n')) {
    let m;
    if ((m = line.match(/^package (?:@\S+ )*([\w.]+) \{/))) { pkg = m[1]; skipPkg = /\.internal\b|\.compose\.runtime\.(?:\w+\.)?(tooling|reflect)\b/.test(pkg); }
    else if (skipPkg) continue;
    else if ((m = line.match(/^  (.*?)\b(?:class|interface|enum|@interface|object)\s+([\w.]+)/))) {
      cls = { name: m[2], facade: /Kt$/.test(m[2]) };
      if (!cls.facade && !m[2].includes('.') && !INTERNAL.test(m[1])) add(m[2], pkg.startsWith('androidx.compose.runtime') ? 'Runtime (state, effects, composition)' : 'Types', lib, m[1]);
    } else if (cls?.facade && (m = line.match(/^    method (.*?)\bpublic static .*? ([\w$-]+)\((.*)\);/))) {
      const [, annots, name, params] = m;
      if (/@BytecodeOnly/.test(annots) || INTERNAL.test(annots) || /[$-]/.test(name) || name.startsWith('_')) continue;
      if (/^androidx\.compose\.ui\.Modifier[,)]?/.test(params) && / androidx\.compose\.ui\.Modifier /.test(line)) add(`Modifier.${name}`, 'Modifiers', lib, annots);
      else if (pkg.startsWith('androidx.compose.runtime')) add(name, 'Runtime (state, effects, composition)', lib, annots);
      else if (/@androidx\.compose\.runtime\.Composable\b/.test(annots) && /^[A-Z]/.test(name) && / void /.test(line)) add(name, 'Composables', lib, annots);
      else add(name, 'Other functions and properties', lib, annots);
    } else if (cls?.facade && (m = line.match(/^    property (.*?)\bpublic static .*? (\w+);/)) && !INTERNAL.test(m[1])) {
      add(m[2], pkg.startsWith('androidx.compose.runtime') ? 'Runtime (state, effects, composition)' : 'Other functions and properties', lib, m[1]);
    }
  }
}
function add(key, section, lib, annots) {
  const flags = { deprecated: /@Deprecated\b/.test(annots), experimental: /@[\w.]*Experimental\w*\b/.test(annots) };
  const cur = api.get(key);
  if (!cur) return api.set(key, { section, libs: new Set([lib]), ...flags });
  cur.libs.add(lib);
  cur.deprecated &&= flags.deprecated; // only when every overload is
  cur.experimental &&= flags.experimental;
}

// Existing rows (by API key) keep their status, issue and notes.
const kept = new Map();
for (const line of readdirSync(dir).filter((f) => f.endsWith('.md')).flatMap((f) => readFileSync(dir + f, 'utf8').split('\n'))) {
  const c = line.split('|').map((s) => s.trim());
  if (c.length >= 7 && c[1].startsWith('`')) kept.set(c[1].replace(/`/g, ''), { status: c[3], issue: c[4], notes: c[5] });
}
for (const [s, f] of Object.entries(FILES)) {
  const rows = [...api].filter(([, v]) => v.section === s).sort(([a], [b]) => a.localeCompare(b));
  writeFileSync(dir + f + '.md', [`# ${s}`, '', INTRO, '', '| API | Library | Android | Issue | Notes |', '|---|---|---|---|---|', ...rows.map(([k, v]) => {
    const row = kept.get(k) || { status: '⬜', issue: '', notes: '' };
    if (!row.notes) row.notes = [v.deprecated && 'Deprecated', v.experimental && 'Experimental'].filter(Boolean).join('; ');
    return `| \`${k}\` | ${[...v.libs].join(', ')} | ${row.status} | ${row.issue} | ${row.notes} |`;
  }), ''].join('\n'));
}

// Record the library versions in the support matrix.
const matrixPath = root + 'docs/compatibility/versions.json';
const matrix = JSON.parse(readFileSync(matrixPath, 'utf8'));
matrix.compose = Object.fromEntries(versions.map((v) => v.split(' ')));
writeFileSync(matrixPath, JSON.stringify(matrix, null, 2) + '\n');
console.log(`${api.size} APIs from ${versions.join(', ')}`);
for (const s of Object.keys(FILES)) console.log(`  ${s}: ${[...api.values()].filter((v) => v.section === s).length}`);
